import { speechText } from '../../src/voice/tts/speechText';

// run: npx tsx tools/unit/voice-speech.test.ts — what is said aloud (ТЗ 6.11.4)
let fail = 0, n = 0;
const eq = (a: string, b: string, lang: 'ru' | 'en' = 'ru') => { n++; const g = speechText(a, lang); if (g !== b) { fail++; console.log(`✗ «${a}» → «${g}» (want «${b}»)`); } };
eq('Фокус 5 мин', 'Фокус 5 минут'); eq('1 мин', '1 минуту'); eq('2 мин', '2 минуты'); eq('21 мин', '21 минуту'); eq('11 мин', '11 минут');
eq('Работал 3 ч', 'Работал 3 часа'); eq('5 ч', '5 часов'); eq('1 ч', '1 час');
eq('Пробежал 5 км', 'Пробежал 5 километров'); eq('12 кг', '12 килограммов'); eq('Выполнено 71%', 'Выполнено 71 процент'); eq('Выполнено 12%', 'Выполнено 12 процентов');
eq('Встреча в 15:00', 'Встреча в 15 часов'); eq('Встреча в 09:05', 'Встреча в 9 ноль 5'); eq('Подъём в 7:30', 'Подъём в 7 30');
eq('✓ Зарядка · Вода → готово', 'Зарядка Вода готово'); eq('«Зарядка» — отмечена', 'Зарядка, отмечена');
eq('Core и Extra', 'кор и экстра'); eq('Pro и VeyrArc', 'про и Вейр-арк'); eq('Задача на 2026-10-29 создана', 'Задача на создана'.replace('на создана', 'на  создана').replace('  ', ' '));
eq('Done 5 min at 15:00', 'Done 5 minutes at 15 o’clock', 'en'); eq('1 min', '1 minute', 'en');
const long = 'Первое предложение про дела. ' + 'Очень длинное второе предложение, которое не помещается целиком в двести двадцать символов и поэтому будет отброшено вместе со всеми остальными словами после него, так что мы говорим только начало. Третье.';
const got = speechText(long, 'ru'); n++;
if (got.length > 220 || !got.endsWith('Подробности на экране.') || !got.startsWith('Первое предложение про дела.')) { fail++; console.log('✗ long text:', got); }
console.log(fail ? `${fail} failed of ${n}` : `all ${n} passed`);
if (fail) process.exit(1);
